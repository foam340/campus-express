const fs = require('fs')
const path = require('path')

const aliases = { development:'dev', dev:'dev', test:'test', production:'prod', prod:'prod' }
const requested = process.argv[2] || 'development'
const alias = aliases[requested]
if (!alias) throw new Error(`Unsupported environment: ${requested}`)

const root = path.resolve(__dirname, '..')
const source = path.join(root, 'config', `env.${alias}.js`)
const target = path.join(root, 'config', 'current.js')
if (!fs.existsSync(source)) throw new Error(`Missing environment file: ${source}`)
fs.writeFileSync(target, `// Generated by scripts/set-env.js\nmodule.exports = require('./env.${alias}')\n`)
console.log(`Environment switched to ${requested}.`)
